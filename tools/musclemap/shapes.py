# Muscle map design on a 100 x 200 canvas per view (head at the top, feet at the bottom).
# Each entry: (kind, points, mirror). kind is a MuscleGroup raw value, "base" (the body
# silhouette, drawn first so the gaps between muscles read as definition lines) or "other"
# (muscles no exercise group trains, e.g. adductors). Points trace a closed outline that is
# smoothed into a curve; mirror=True also draws the shape flipped (x -> 100 - x).
# The shapes are drawn for the left half of the picture. geometry.py fits the muscles together
# with thin, even gaps and rounds them off.
import math

def oval(cx, cy, rx, ry, tilt=0.0, n=14):
    """An ellipse; tilt (degrees) leans its long axis like a limb hanging out to the left."""
    a = math.radians(tilt)
    pts = []
    for i in range(n):
        t = 2 * math.pi * i / n
        x, y = rx * math.cos(t), ry * math.sin(t)
        pts.append((round(cx + x * math.cos(a) - y * math.sin(a), 2), round(cy + x * math.sin(a) + y * math.cos(a), 2)))
    return pts

def along(a, b, pts):
    """Points given along a limb: t runs from a (0) to b (1), s is the distance out to the side
    (positive away from the body, i.e. towards the left of the picture)."""
    dx, dy = b[0] - a[0], b[1] - a[1]
    length = math.hypot(dx, dy)
    ux, uy = dx / length, dy / length
    nx, ny = -uy, ux
    if nx > 0:
        nx, ny = -nx, -ny
    return [(round(a[0] + dx * t + nx * d, 2), round(a[1] + dy * t + ny * d, 2)) for t, d in pts]

def sym(left):
    """A shape that straddles the centre line, from its left half (top centre to bottom centre)."""
    right = [(round(100 - x, 2), y) for x, y in reversed(left) if abs(x - 50) > 0.01]
    return left + right

